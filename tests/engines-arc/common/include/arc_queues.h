/*
 * Actually there are 4 MME engines in the SoC however two
 * of them are used in Slave mode, so from the SW point of
 * view there are only two MMEs
 */
#define ARC_MME_COUNT			2

#define ARC_TPC_COUNT_PER_DCORE		6
#define ARC_TPC_COUNT			(4*ARC_TPC_COUNT_PER_DCORE)

#define ARC_NIC_COUNT_PER_DCORE		6
#define ARC_NIC_COUNT			(4*ARC_NIC_COUNT_PER_DCORE)

/*
 * Rotator blocks are not part of DCore
 * its in the shared block
 */
#define ARC_RTR_COUNT			2

/*
 * EDMAs are for transfers within the SoC memories
 */
#define ARC_EDMA_COUNT_PER_DCORE	2
#define ARC_EDMA_COUNT			(4*ARC_EDMA_COUNT_PER_DCORE)

/*
 * Note: There are only 2 PDMAs in the SoC
 * One DMA is used for data transfer from Host to Device
 * other for Device to Host
 */
#define ARC_PDMA_COUNT			2

#define TOTAL_ENGINE_COUNT		(ARC_MME_COUNT + ARC_TPC_COUNT + \
					 ARC_NIC_COUNT + \
					 ARC_RTR_COUNT + ARC_DDMA_COUNT + \
					 ARC_PDMA_COUNT)


