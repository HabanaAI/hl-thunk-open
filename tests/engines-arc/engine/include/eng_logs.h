#ifndef __ENG_LOGS_H__
#define __ENG_LOGS_H__

#define ENG_MAIN_ENTRY			0x000000FF

/*
 * Pre Init codes
 * 0x100 to 0xFFF
 */
#define ENG_CTXT_PRE_INIT_ENTRY		0x00000100
#define ENG_CTXT_UNKNOWN_CPU_ID		0x00000101
#define ENG_CTXT_PRE_INIT_EXIT		0x000001FF

#define ENG_REGS_PRE_INIT_ENTRY		0x00000200
#define ENG_REGS_PRE_INIT_EXIT		0x000002FF

#define ENG_QUEUES_PRE_INIT_ENTRY		0x00000300
#define ENG_QUEUES_PRE_INIT_EXIT		0x000003FF

#define ENG_SYNC_MNGR_PRE_INIT_ENTRY		0x00000400
#define ENG_SYNC_MNGR_PRE_INIT_EXIT		0x000004FF

#define ENG_DMA_PRE_INIT_ENTRY		0x00000400
#define ENG_DMA_PRE_INIT_EXIT			0x000004FF

/*
 * Pre init success: 0x00010000
 */
#define ENG_PRE_INIT_COMPLETED          0x00010000

/*
 * Post init codes
 * 0x10001 to 0x1FFFF
 */
#define ENG_POST_INIT_SCHEMA_MISMATCH	0x00010001

#define ENG_CTXT_POST_INIT_ENTRY		0x00010100
#define ENG_CTXT_POST_INIT_EXIT		0x000101FF

#define ENG_REGS_POST_INIT_ENTRY		0x00010200
#define ENG_REGS_POST_INIT_EXIT		0x000102FF

#define ENG_QUEUES_POST_INIT_ENTRY		0x00010300
#define ENG_QUEUES_POST_INIT_EXIT		0x000103FF

#define ENG_SYNC_MNGR_POST_INIT_ENTRY		0x00010400
#define ENG_SYNC_MNGR_POST_INIT_EXIT		0x000104FF

#define ENG_DMA_POST_INIT_ENTRY		0x00010400
#define ENG_DMA_POST_INIT_EXIT		0x000104FF

/*
 * Post init success: 0x00020000
 */
#define ENG_POST_INIT_COMPLETED 	0x00020000

#endif /* __ENG_LOGS_H__ */
