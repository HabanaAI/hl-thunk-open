#ifndef __SCHED_LOGS_H__
#define __SCHED_LOGS_H__

#define SCHED_MAIN_ENTRY			0x000000FF

/*
 * Pre Init codes
 * 0x100 to 0xFFF
 */
#define SCHED_CTXT_PRE_INIT_ENTRY		0x00000100
#define SCHED_CTXT_UNKNOWN_CPU_ID		0x00000101
#define SCHED_CTXT_PRE_INIT_EXIT		0x000001FF

#define SCHED_REGS_PRE_INIT_ENTRY		0x00000200
#define SCHED_REGS_PRE_INIT_EXIT		0x000002FF

#define SCHED_QUEUES_PRE_INIT_ENTRY		0x00000300
#define SCHED_QUEUES_PRE_INIT_EXIT		0x000003FF

#define SCHED_SYNC_MNGR_PRE_INIT_ENTRY		0x00000400
#define SCHED_SYNC_MNGR_PRE_INIT_EXIT		0x000004FF

#define SCHED_DMA_PRE_INIT_ENTRY		0x00000400
#define SCHED_DMA_PRE_INIT_EXIT			0x000004FF

/*
 * Pre init success: 0x00010000
 */
#define SCHED_PRE_INIT_COMPLETED        0x00010000

/*
 * Post init codes
 * 0x10001 to 0x1FFFF
 */
#define SCHED_POST_INIT_SCHEMA_MISMATCH	0x00010001

#define SCHED_CTXT_POST_INIT_ENTRY		0x00010100
#define SCHED_CTXT_POST_INIT_EXIT		0x000101FF

#define SCHED_REGS_POST_INIT_ENTRY		0x00010200
#define SCHED_REGS_POST_INIT_EXIT		0x000102FF

#define SCHED_QUEUES_POST_INIT_ENTRY		0x00010300
#define SCHED_QUEUES_POST_INIT_EXIT		0x000103FF

#define SCHED_SYNC_MNGR_POST_INIT_ENTRY		0x00010400
#define SCHED_SYNC_MNGR_POST_INIT_EXIT		0x000104FF

#define SCHED_DMA_POST_INIT_ENTRY		0x00010400
#define SCHED_DMA_POST_INIT_EXIT		0x000104FF

/*
 * Post init success: 0x00020000
 */
#define SCHED_POST_INIT_COMPLETED       0x00020000

#endif /* __REGS_H__ */
